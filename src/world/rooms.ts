export const bellSequence = [0, 2, 1];
export function ringBell(
  progress: number[],
  note: number,
): { progress: number[]; solved: boolean } {
  const next = [...progress, note];
  if (next.every((n, i) => n === bellSequence[i]))
    return { progress: next, solved: next.length === 3 };
  return { progress: note === bellSequence[0] ? [note] : [], solved: false };
}
